    private static final int[] DX = {0, 1, 0, -1}; // 0 上, 1 右, 2 下, 3 左
    private static final int[] DY = {-1, 0, 1, 0};

    private char[][] ground;   // '#' 墙, '.' 目标, ' ' 地板
    private boolean[][] box;
    private boolean[][] inside; // 从玩家能走到的区域（关卡边界内的地板）
    private int cols, rows, px, py;
    private int level, moves;
    private int[] hist = new int[4096];
    private int hn;
    private boolean win, running;
    private int cell, ox, oy;
    private int anim; // 过关后的闪烁计时

    SokobanCanvas() { load(0); }

    void start() {
        if (running) return;
        running = true;
        new Thread(this).start();
    }
    void stop() { running = false; }

    public void run() {
        while (running) {
            if (win) anim++;
            repaint();
            try { Thread.sleep(win ? 90 : 160); } catch (InterruptedException e) { }
        }
    }

    // ---------------- 关卡 ----------------

    private void load(int idx) {
        if (idx < 0) idx = 0;
        if (idx >= LEVELS.length) idx = LEVELS.length - 1;
        level = idx;
        String s = LEVELS[idx];

        // 行数与最大宽 —— CLDC 没有 String.split，手工扫
        int n = 1, w = 0, cur = 0;
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            if (ch == '\n') {
                if (cur > w) w = cur;
                cur = 0;
                n++;
            } else cur++;
        }
        if (cur > w) w = cur;
        cols = w;
        rows = n;

        ground = new char[rows][cols];
        box = new boolean[rows][cols];
        for (int r = 0; r < rows; r++)
            for (int c = 0; c < cols; c++) ground[r][c] = ' ';

        int r = 0, c = 0;
        px = 0; py = 0;
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            if (ch == '\n') { r++; c = 0; continue; }
            if (r < rows && c < cols) {
                if (ch == '#') ground[r][c] = '#';
                else if (ch == '.') ground[r][c] = '.';
                else if (ch == '$') box[r][c] = true;
                else if (ch == '*') { ground[r][c] = '.'; box[r][c] = true; }
                else if (ch == '@') { px = c; py = r; }
                else if (ch == '+') { ground[r][c] = '.'; px = c; py = r; }
            }
            c++;
        }
        moves = 0;
        hn = 0;
        win = false;
        anim = 0;
        flood();
    }

    /**
     * 标记玩家可达区域。关卡文本里「墙外的空格」和「墙内的地板」都是空格，
     * 只能靠连通性区分 —— 不区分的话会在关卡外围画出一圈多余的地板。
     */
    private void flood() {
        inside = new boolean[rows][cols];
        int[] qx = new int[rows * cols];
        int[] qy = new int[rows * cols];
        int head = 0, tail = 0;
        qx[tail] = px; qy[tail] = py; tail++;
        inside[py][px] = true;
        while (head < tail) {
            int x = qx[head], y = qy[head];
            head++;
            for (int d = 0; d < 4; d++) {
                int nx = x + DX[d], ny = y + DY[d];
                if (nx < 0 || ny < 0 || nx >= cols || ny >= rows) continue;
                if (inside[ny][nx]) continue;
                if (ground[ny][nx] == '#') continue;
                inside[ny][nx] = true;
                qx[tail] = nx; qy[tail] = ny; tail++;
            }
        }
    }

    private boolean free(int x, int y) {
        if (x < 0 || y < 0 || x >= cols || y >= rows) return false;
        if (ground[y][x] == '#') return false;
        return inside[y][x];
    }

    private boolean allOnGoal() {
        for (int r = 0; r < rows; r++)
            for (int c = 0; c < cols; c++)
                if (box[r][c] && ground[r][c] != '.') return false;
        return true;
    }

    // ---------------- 操作 ----------------

    private void move(int d) {
        int nx = px + DX[d], ny = py + DY[d];
        if (!free(nx, ny)) return;
        boolean pushed = false;
        if (box[ny][nx]) {
            int bx = nx + DX[d], by = ny + DY[d];
            if (!free(bx, by) || box[by][bx]) return;
            box[ny][nx] = false;
            box[by][bx] = true;
            pushed = true;
        }
        px = nx;
        py = ny;
        moves++;
        if (hn < hist.length) hist[hn++] = d | (pushed ? 4 : 0);
        if (allOnGoal()) { win = true; anim = 0; }
    }

    /**
     * 撤销。推过箱子的那一步要连箱子一起退回去：
     * 推箱子时玩家从 A 到 B、箱子从 B 到 C，撤销就是玩家 B→A、箱子 C→B。
     * 只退玩家不退箱子，箱子会留在 C 而玩家回到 A，再推一次就穿模了。
     */
    private void undo() {
        if (hn == 0) return;
        int h = hist[--hn];
        int d = h & 3;
        if ((h & 4) != 0) {
            int cx = px + DX[d], cy = py + DY[d];
            if (cx >= 0 && cy >= 0 && cx < cols && cy < rows) {
                box[cy][cx] = false;
                box[py][px] = true;
            }
        }
        px -= DX[d];
        py -= DY[d];
        if (moves > 0) moves--;
        win = false;
    }

    // ---------------- 绘制 ----------------

    protected void paint(Graphics g) {
        int w = getWidth(), h = getHeight();
        g.setColor(0x0B1016);
        g.fillRect(0, 0, w, h);

        int top = 28, bottom = 22;
        cell = Math.min((w - 10) / cols, (h - top - bottom) / rows);
        if (cell < 6) cell = 6;
        ox = (w - cell * cols) / 2;
        oy = top + (h - top - bottom - cell * rows) / 2;
        if (oy < top) oy = top;

        for (int r = 0; r < rows; r++) {
            for (int c = 0; c < cols; c++) {
                int x = ox + c * cell, y = oy + r * cell;
                char gr = ground[r][c];
                if (gr == '#') {
                    g.setColor(0x26323F);
                    g.fillRect(x, y, cell, cell);
                    g.setColor(0x33424F);
                    g.drawRect(x, y, cell - 1, cell - 1);
                } else if (inside[r][c]) {
                    g.setColor(0x161F29);
                    g.fillRect(x, y, cell, cell);
                    if (gr == '.') {
                        // 目标：中心菱形，比箱子小一圈，箱子压上去仍然看得出"对上了"
                        int s = Math.max(3, cell / 3);
                        g.setColor(0x2E8F63);
                        g.fillRect(x + (cell - s) / 2, y + (cell - s) / 2, s, s);
                    }
                }
            }
        }

        // 箱子在目标上要换成绿色 —— 这是玩家判断进度的唯一视觉依据
        for (int r = 0; r < rows; r++) {
            for (int c = 0; c < cols; c++) {
                if (!box[r][c]) continue;
                int x = ox + c * cell, y = oy + r * cell;
                boolean ok = ground[r][c] == '.';
                int pad = cell > 14 ? 2 : 1;
                g.setColor(ok ? 0x3ECF8E : 0xB5814A);
                g.fillRect(x + pad, y + pad, cell - pad * 2, cell - pad * 2);
                g.setColor(ok ? 0x7BE8B6 : 0xD9A66B);
                g.drawRect(x + pad, y + pad, cell - pad * 2 - 1, cell - pad * 2 - 1);
            }
        }

        // 玩家：圆形。过关时闪两下，比弹一个文字框更像"通了"
        if (!win || (anim / 3) % 2 == 0) {
            int d2 = cell - (cell > 12 ? 4 : 2);
            g.setColor(0x4FD1C5);
            g.fillArc(ox + px * cell + (cell - d2) / 2, oy + py * cell + (cell - d2) / 2,
                      d2, d2, 0, 360);
        }

        g.setColor(0xE6EDF3);
        Font f = Font.getFont(Font.FACE_PROPORTIONAL, Font.STYLE_BOLD, Font.SIZE_SMALL);
        g.setFont(f);
        g.drawString("推箱子  " + (level + 1) + "/" + LEVELS.length + "   步 " + moves,
                     w / 2, 6, Graphics.TOP | Graphics.HCENTER);

        int msgY = h - f.getHeight() - 4;
        if (win) {
            g.setColor(0x3ECF8E);
            g.drawString(level + 1 >= LEVELS.length ? "全部通关！按 OK 回第 1 关" : "过关！按 OK 下一关",
                         w / 2, msgY, Graphics.TOP | Graphics.HCENTER);
        } else {
            g.setColor(0x6B7A89);
            g.drawString("左软键撤销 · 右软键重开", w / 2, msgY, Graphics.TOP | Graphics.HCENTER);
        }
    }

    protected void keyPressed(int key) {
        int a = 0;
        try { a = getGameAction(key); } catch (Exception e) { }

        if (a == UP) move(0);
        else if (a == RIGHT) move(1);
        else if (a == DOWN) move(2);
        else if (a == LEFT) move(3);
        else if (key == KEY_NUM5 || a == FIRE) {
            if (win) load(level + 1 >= LEVELS.length ? 0 : level + 1);
            else undo();
        } else if (key == -6 || key == -21) {
            undo();
        } else if (key == -7 || key == -22) {
            load(level);
        }
    }
